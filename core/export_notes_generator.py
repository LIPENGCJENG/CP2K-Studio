"""Readable delivery notes based on actual package files and execution settings."""
from core.run_script_generator import INPUT_FILENAME, run_command
from i18n.messages import i18n_msg


def vibrational_export_notes(project):
    if project.global_settings.run_type != 'VIBRATIONAL_ANALYSIS':
        return ''
    v = project.vibrational
    note = i18n_msg('7. VIBRATIONAL ANALYSIS\nMode: {mode}\nDX: {dx} bohr; NPROC_REP: {ranks} MPI ranks per replica (not replica count).\nMOLDEN_VIB: {molden}; HESSIAN: {hessian}.\nAfter a successful CP2K calculation, output.out contains frequencies and, when requested, IR/Raman intensities. MOLDEN_VIB writes normal modes for Molden; HESSIAN writes a CP2K binary .hess file. Actual filenames follow CP2K project/print conventions. No spectrum image or broadened spectrum is generated by Studio.\nNo results are included: CP2K has not run. Use a tightly optimized stationary structure and test SCF, grid, displacement and response convergence. Saved GEO_OPT fixed atoms are ignored; all atoms enter the full Hessian. IR/Raman response has not been numerically verified by Studio. XML validity does not establish a successful intensity calculation.\n', code='vib.export_notes', mode=v.spectra_label, dx=v.dx, ranks=v.nproc_rep,
                    molden='ON' if v.molden_vib else 'OFF', hessian='ON' if v.hessian else 'OFF')
    if project.structure.periodic == 'XYZ' and v.intensities:
        note += i18n_msg('Periodic intensity path: {mode}, CELL/PERIODIC XYZ, Quickstep/GPW with implicit Gamma-point sampling. IR uses MOMENTS/PERIODIC T and MAX_MOMENT 1; Raman uses LINRES/POLAR/PERIODIC_DIPOLE_OPERATOR T. IR and Raman are independent options; when both are selected, both property sections share one vibrational Hessian workflow.\nUse an insulating, gapped structure with integer occupations. Inspect Berry-phase polarization branch continuity for IR. FULLY_PERIODIC controls Hessian rotations and is retained as explicitly configured, not enabled automatically. Periodic Raman support is experimental; verify CP2K build capabilities and numerical response/intensity convergence. No numerical intensity calculation has been performed by Studio.\n', code='vib.periodic_export_notes', mode=v.spectra_label)
    # Delivery files remain independent of the current UI language. New task
    # guidance is bilingual; existing ENERGY/GEO_OPT notes are unchanged.
    return '\n' + note.render('en_US') + '\n' + note.render('zh_CN')


def cell_optimization_export_notes(project):
    if project.global_settings.run_type != 'CELL_OPT':
        return ''
    config = project.cell_opt
    note = i18n_msg('7. CELL OPTIMIZATION\nCoordinates and cell vectors are optimized together with ANALYTICAL stress. The obsolete CELL_OPT / TYPE keyword is not emitted.\nExternal pressure: {pressure} bar; pressure tolerance: {tolerance} bar.\nOnly 3D PERIODIC XYZ with Quickstep/GPW and POISSON_SOLVER PERIODIC is supported by this release.\nFIXED_ATOMS, when present, constrain fractional coordinates; their Cartesian positions may move with the cell. KEEP_SYMMETRY refers to the explicitly selected initial cell symmetry, not the atomic space group.\ninput.inp and structure.xyz contain the INITIAL structure. Optimized cells, stresses and optimization steps are produced only by an actual CP2K run; inspect output.out and CP2K restart/trajectory files and confirm convergence. No calculation or geometry optimization has been run by Studio.\nTest stress, basis, grid, SCF and Brillouin-zone sampling convergence; the generated GPW input uses Gamma-point sampling.\n', code='cellopt.export_notes', pressure=config.external_pressure, tolerance=config.pressure_tolerance)
    return '\n' + note.render('en_US') + '\n' + note.render('zh_CN')


def md_export_notes(project):
    if project.global_settings.run_type != 'MD':
        return ''
    md = project.md
    note = i18n_msg('7. BORN–OPPENHEIMER AIMD\nEnsemble: {ensemble}; steps: {steps}; timestep: {dt} fs; duration: {duration} ps; temperature: {temperature} K.\nNVT uses CSVR; NVE has no thermostat and TEMPERATURE only initializes absent velocities.\nTrajectory: {trajectory}, format {format}, interval {interval} steps. Restart output: {restart}, interval {restart_interval} steps, backup copies {copies}.\nCP2K produces trajectory files (typically project-pos-1.xyz or EXTXYZ) and project-1.ener containing step/time, temperature, kinetic energy, potential energy and conserved quantity. In NVE, also inspect kinetic plus potential energy drift; in NVT, conserved quantity includes the thermostat contribution. Actual filenames follow CP2K print conventions. No trajectory, energies or other calculation results are included in this package.\nContinuation: {continuation}. When enabled, EXT_RESTART restores coordinates, velocities, cell and counters; CSVR energy and RNG state are restored explicitly for NVT. STEPS counts additional steps from the restored counter. The viewer and structure.xyz show the project structure, while CP2K reads restart positions at runtime. WFN restart is independent; SCF_GUESS is not changed. Verify electronic settings and physical continuity after resuming; XML and static restart checks are not a runtime verification.\nRun each segment in a fresh package directory. Studio does not concatenate trajectories or implement output appending. Keep the source restart and previous output files separately.\nTest timestep, SCF and grid convergence. NVE needs energy-drift checks; NVT needs temperature and equilibration checks. Simulation length alone does not establish statistical equilibrium. FIXED_ATOMS are retained in fractional coordinates.\n', code='md.export_notes',
        ensemble=md.ensemble, steps=md.steps, dt=md.timestep, duration=md.simulation_time_ps,
        temperature=md.temperature, trajectory=md.write_trajectory, format=md.trajectory_format,
        interval=md.trajectory_interval, restart=md.write_restart, restart_interval=md.restart_interval,
        copies=md.backup_copies, continuation=md.continue_from_restart)
    return '\n' + note.render('en_US') + '\n' + note.render('zh_CN')


def generate_export_notes(project, package_files, warnings=(), external_dependencies=()):
    config = project.run_environment
    platform_note = {
        'linux': 'Linux / Rocky Linux: enter the package directory in a Bash terminal and run bash run.sh.',
        'macos': 'macOS: install compatible CP2K and MPI; enter the package directory and run bash run.sh.',
        'wsl2': 'Windows / WSL2: enter the package directory in the WSL2 Linux terminal and run bash run.sh.\n'
                'Native Windows PowerShell cannot execute this script as a Bash script.',
    }[config.operating_system]
    external = list(dict.fromkeys(external_dependencies))
    dependency_note = ('External dependencies NOT copied; this package is not self-contained:\n' +
                       '\n'.join('  ' + str(p) for p in external) if external else
                       'Selected basis/potential data and structure files are included using relative paths.\n'
                       'CP2K and MPI executables must be supplied by the target environment.')
    return f'''CP2K Studio - Export Notes
=====================================

1. PROJECT INFORMATION
Project: {project.global_settings.project_name}
CP2K Version: {project.cp2k_version}
Run Type: {project.global_settings.run_type}
Entry Input: {INPUT_FILENAME}
Coordinates: Angstrom
Input passed XML syntax validation; CP2K has NOT been executed.
Multiple potential sources, when used, are merged into studio_potentials.dat;
source files and fingerprints remain recorded in the project.

2. PACKAGE CONTENTS
{chr(10).join('  ' + name for name in sorted(package_files))}

{dependency_note}

3. RUN CONFIGURATION
Operating System: {config.os_label}
MPI Processes: {config.mpi_processes}
OpenMP Threads per Process: {config.omp_threads}
Required Logical CPU Slots: {config.required_cpu_slots}
Execution Mode: {config.execution_mode}
CPU slots = MPI processes x OpenMP threads; these are execution slots, not physical core counts.

4. HOW TO RUN
Open a terminal in the calculation package directory, then execute:

bash run.sh

Equivalent command from the package directory:
{run_command(config)}

{platform_note}
After moving or unzipping the whole package, bash run.sh still works without execute permissions.
Prerequisites:
- CP2K installed with cp2k.psmp available through PATH.
- MPI installed with mpirun available through PATH.
- MPI launcher compatible with the MPI implementation used to build CP2K.
- Correct basis, potential and structure paths, including any external dependencies above.
- Sufficient CPU execution slots and memory on the target machine.

5. OUTPUT FILES
output.out: CP2K output log after a successful launch.
Other files depend on the project and CP2K print settings.
Startup errors appear in the terminal; nonzero exit statuses are returned to the caller.

6. TROUBLESHOOTING
cp2k.psmp: command not found -> install CP2K psmp and check PATH.
mpirun: command not found -> install a compatible MPI and check PATH.
Input file not found -> restore input.inp alongside run.sh.
Basis set file not found -> check BASIS_SET_FILE_NAME and packaged/external data files.
Potential file not found -> check POTENTIAL_FILE_NAME and packaged/external data files.
MPI/resource failures -> check MPI compatibility and target resource allocation.
Script generation and XML syntax checks do not guarantee scientific accuracy or convergence.

Configuration warnings:
{chr(10).join(str(w) for w in warnings) or 'None.'}
''' + vibrational_export_notes(project) + cell_optimization_export_notes(project) + md_export_notes(project)
