"""XML settings live in a dialog; changes are committed only after verification."""
from i18n.messages import i18n_msg, i18n_str
from PySide6.QtCore import Qt
from i18n.qt import (QDialog, QVBoxLayout, QHBoxLayout, QFormLayout, QLabel,
    QRadioButton, QLineEdit, QPushButton, QFileDialog, QDialogButtonBox)
from core.schema import CP2KSchema, BUNDLED_XML


class XMLDialog(QDialog):
    def __init__(self, current_path=None, parent=None):
        super().__init__(parent)
        self.setWindowTitle(i18n_msg('XML Schema · CP2K 2026.1', code='studio.9219baf48a5d736a'))
        self.resize(700, 390)
        self.selected_path = current_path
        layout = QVBoxLayout(self)
        title = QLabel(i18n_msg('CP2K 2026.1 · XML Schema', code='studio.49e19bfec4131089'))
        title.setObjectName('heading')
        layout.addWidget(title)
        self.builtin = QRadioButton(i18n_msg('Use Bundled CP2K 2026.1 XML', code='studio.63fe2caa9ad240e6'))
        self.custom = QRadioButton(i18n_msg('Use Verified Custom XML', code='studio.47275797813649bf'))
        layout.addWidget(self.builtin)
        layout.addWidget(self.custom)
        row = QHBoxLayout()
        self.path = QLineEdit(current_path or '')
        self.path.setPlaceholderText(i18n_msg('Choose an XML file generated by CP2K 2026.1', code='studio.a27b42f2bb23b5c8'))
        row.addWidget(self.path)
        browse = QPushButton(i18n_msg('Browse File…', code='studio.29d75b8eb8866bb4'))
        browse.clicked.connect(self.browse)
        row.addWidget(browse)
        layout.addLayout(row)
        form = QFormLayout()
        self.source = QLabel()
        self.actual_path = QLabel()
        self.actual_path.setWordWrap(True)
        self.version = QLabel(i18n_msg('Not Checked', code='studio.cdbc0434f568fc9e'))
        self.status = QLabel()
        self.status.setWordWrap(True)
        for label, widget in [(i18n_msg('Source', code='studio.a488e93d69cc1296'), self.source), (i18n_msg('XML File', code='studio.7a58742e7c1d52c3'), self.actual_path),
                              (i18n_msg('Schema Version', code='studio.64f58bcd239b5eb0'), self.version), (i18n_msg('Load Status', code='studio.a52bef0c615ce659'), self.status)]:
            widget.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
            form.addRow(label, widget)
        layout.addLayout(form)
        row = QHBoxLayout()
        check = QPushButton(i18n_msg('Check Schema', code='studio.33a2c664588eb925'))
        check.clicked.connect(self.check_schema)
        row.addWidget(check)
        restore = QPushButton(i18n_msg('Restore Default XML', code='studio.f08618fa6f089d26'))
        restore.clicked.connect(self.restore_default)
        row.addWidget(restore)
        layout.addLayout(row)
        note = QLabel(i18n_msg('Only target version 2026.1 is accepted. Schema changes do not modify the structure, calculation parameters, or INP preview; cancelling preserves project settings.', code='studio.a79dcca298bc393d'))
        note.setWordWrap(True)
        layout.addWidget(note)
        self.buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel)
        self.buttons.accepted.connect(self.accept)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
        self.builtin.toggled.connect(self.pending)
        self.custom.toggled.connect(self.pending)
        self.path.textChanged.connect(self.path_edited)
        (self.custom if current_path else self.builtin).setChecked(True)
        self.check_schema()

    def candidate(self):
        return self.path.text().strip() if self.custom.isChecked() else None

    def pending(self, *_):
        self.path.setEnabled(self.custom.isChecked())
        self.source.setText(i18n_msg('Custom File', code='studio.f20216fd37e725fc') if self.custom.isChecked() else i18n_msg('Bundled Official Schema', code='studio.81c441462ada0138'))
        self.actual_path.setText((self.candidate() or i18n_msg('No file selected', code='studio.a96f374e86bc73e4')) if self.custom.isChecked() else i18n_str(BUNDLED_XML))
        self.version.setText(i18n_msg('Not Checked', code='studio.cdbc0434f568fc9e'))
        self.status.setText(i18n_msg('Pending check; version and required Sections will be verified before confirmation.', code='studio.1f2af1396020a712'))

    def path_edited(self, *_):
        self.custom.setChecked(True)
        self.pending()

    def browse(self):
        path, _ = QFileDialog.getOpenFileName(self, i18n_msg('Choose CP2K 2026.1 XML', code='studio.4bf4e106ebc7d18d'), '', 'XML (*.xml)')
        if path:
            self.path.setText(path)
            self.custom.setChecked(True)
            self.check_schema()

    def restore_default(self):
        self.builtin.setChecked(True)
        self.check_schema()

    def check_schema(self):
        try:
            path = self.candidate()
            if self.custom.isChecked() and not path:
                raise ValueError(i18n_msg('Select a custom XML file', code='studio.05f6d1958b9968bd'))
            schema = CP2KSchema(path)
            for section in ['GLOBAL', 'FORCE_EVAL/DFT/SCF', 'MOTION/GEO_OPT']:
                schema.section(section)
            self.source.setText(i18n_msg('Custom File', code='studio.f20216fd37e725fc') if path else i18n_msg('Bundled Official Schema', code='studio.81c441462ada0138'))
            self.actual_path.setText(i18n_str(schema.path))
            self.version.setText(schema.version)
            self.status.setText(i18n_msg('Load check passed · Version 2026.1 and required Sections confirmed', code='studio.3e08d2e223a47c6b'))
            self.status.setStyleSheet('color:#83e1d9;')
            return i18n_str(schema.path) if path else None, True
        except Exception as exc:
            self.version.setText(i18n_msg('Target Version Not Confirmed', code='studio.ba8a821987167ac7'))
            self.status.setText(i18n_msg('Load failed: {p0}', code='studio.91df1b36811ee28b', p0=exc))
            self.status.setStyleSheet('color:#f0a69b;')
            return None, False

    def accept(self):
        path, valid = self.check_schema()
        if valid:
            self.selected_path = path
            super().accept()
